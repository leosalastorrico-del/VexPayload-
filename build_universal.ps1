# Build the single-file universal stager.
# Can be called with default dist paths, or with campaign-specific stagers.
param(
    [string]$X64Stager = "",
    [string]$X86Stager = "",
    [string]$OutFile = "dist\universal_stager.exe",
    [string]$WorkDir = "build\universal",
    [switch]$Sign,
    [string]$Pfx = "",
    [string]$Password = "",
    [switch]$Test
)

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $MyInvocation.MyCommand.Path
$MSBuild = "D:\VisualStudio2022\MSBuild\Current\Bin\amd64\MSBuild.exe"
if (-not (Test-Path $MSBuild)) { throw "MSBuild not found at $MSBuild" }

function FullPath([string]$p) {
    if ([IO.Path]::IsPathRooted($p)) { return [IO.Path]::GetFullPath($p) }
    return [IO.Path]::GetFullPath((Join-Path $Root $p))
}

if (-not $X64Stager) { $X64Stager = Join-Path $Root "dist\stager.exe" }
if (-not $X86Stager) { $X86Stager = Join-Path $Root "dist\stager_x86.exe" }
$X64Stager = FullPath $X64Stager
$X86Stager = FullPath $X86Stager
$OutFile = FullPath $OutFile
$WorkDir = FullPath $WorkDir

if (-not (Test-Path $X64Stager)) { throw "missing x64 stager: $X64Stager" }
if (-not (Test-Path $X86Stager)) { throw "missing x86 stager: $X86Stager" }
New-Item -ItemType Directory -Force -Path $WorkDir | Out-Null
New-Item -ItemType Directory -Force -Path (Split-Path -Parent $OutFile) | Out-Null

$id = [guid]::NewGuid().ToString("N")
$rc = Join-Path $WorkDir "universal_$id.rc"
$outDir = Join-Path $WorkDir "out_$id"
New-Item -ItemType Directory -Force -Path $outDir | Out-Null

$rcText = @"
// Generated by build_universal.ps1.
101 RCDATA "$($X64Stager -replace '\\','\\')"
102 RCDATA "$($X86Stager -replace '\\','\\')"
"@
[IO.File]::WriteAllText($rc, $rcText, [Text.UTF8Encoding]::new($false))

& $MSBuild (Join-Path $Root "universal_stager.vcxproj") `
    /p:Configuration=Release /p:Platform=Win32 `
    /p:UniversalRc=$rc /p:OutDir=$outDir\ /m /v:m /nologo
if ($LASTEXITCODE -ne 0) { throw "universal stager build failed (exit $LASTEXITCODE)" }

$built = Join-Path $outDir "universal_stager.exe"
if (-not (Test-Path $built)) { throw "universal stager output missing: $built" }
Copy-Item $built $OutFile -Force

$x64Hash = (Get-FileHash $X64Stager -Algorithm SHA256).Hash
$x86Hash = (Get-FileHash $X86Stager -Algorithm SHA256).Hash
$outHash = (Get-FileHash $OutFile -Algorithm SHA256).Hash
$commit = (git -C $Root rev-parse --short HEAD 2>$null)
$meta = [ordered]@{
    schema = 1
    created = (Get-Date).ToUniversalTime().ToString("o")
    commit = "$commit"
    universal = [ordered]@{
        path = $OutFile
        size = (Get-Item $OutFile).Length
        sha256 = $outHash
    }
    embedded = [ordered]@{
        x64 = [ordered]@{ path = $X64Stager; size = (Get-Item $X64Stager).Length; sha256 = $x64Hash }
        x86 = [ordered]@{ path = $X86Stager; size = (Get-Item $X86Stager).Length; sha256 = $x86Hash }
    }
}
$jsonPath = [IO.Path]::ChangeExtension($OutFile, ".json")
$meta | ConvertTo-Json -Depth 6 | Set-Content $jsonPath -Encoding UTF8

$line = "universal: $($meta.universal.size) bytes sha256 $outHash`r`nembedded x64: $x64Hash`r`nembedded x86: $x86Hash"
$line | Set-Content (Join-Path (Split-Path -Parent $OutFile) "BUILD_UNIVERSAL.txt") -Encoding UTF8
Write-Host $line -ForegroundColor Green

if ($Sign) {
    if (-not $Pfx) { throw "-Sign requires -Pfx <certificate.pfx>" }
    & (Join-Path $Root "tools\sign.ps1") -Pfx $Pfx -Password $Password -Targets @($OutFile)
    if ($LASTEXITCODE -ne 0) { throw "universal signing failed" }
}

if ($Test) {
    & $OutFile --selftest --no-elevate
    if ($LASTEXITCODE -ne 0) { throw "universal x64 selftest failed ($LASTEXITCODE)" }
    & $OutFile --arch x86 --selftest --no-elevate
    if ($LASTEXITCODE -ne 0) { throw "universal x86 selftest failed ($LASTEXITCODE)" }
    & $OutFile --safe --no-elevate
    if ($LASTEXITCODE -ne 2) { throw "universal --safe expected 2, got $LASTEXITCODE" }
    Write-Host "[*] universal launcher tests passed" -ForegroundColor Green
}
exit 0
