# Build the single-file universal stager.
# Prerequisite: build.ps1 and build_x86.ps1 have produced dist\stager.exe and
# dist\stager_x86.exe. The launcher is 32-bit so it can start either native
# payload from one distributed file.
param(
    [switch]$Test
)

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $MyInvocation.MyCommand.Path
$MSBuild = "D:\VisualStudio2022\MSBuild\Current\Bin\amd64\MSBuild.exe"
if (-not (Test-Path $MSBuild)) { throw "MSBuild not found at $MSBuild" }

$x64 = Join-Path $Root "dist\stager.exe"
$x86 = Join-Path $Root "dist\stager_x86.exe"
if (-not (Test-Path $x64)) { throw "missing dist\stager.exe; run build.ps1 first" }
if (-not (Test-Path $x86)) { throw "missing dist\stager_x86.exe; run build_x86.ps1 first" }

$buildDir = Join-Path $Root "build"
New-Item -ItemType Directory -Force -Path $buildDir | Out-Null
$rc = Join-Path $buildDir "universal_stager.rc"
$rcText = @"
// Generated by build_universal.ps1. Both stagers are embedded as RCDATA.
101 RCDATA "$($x64 -replace '\\','\\')"
102 RCDATA "$($x86 -replace '\\','\\')"
"@
[IO.File]::WriteAllText($rc, $rcText, [Text.UTF8Encoding]::new($false))

& $MSBuild (Join-Path $Root "universal_stager.vcxproj") /p:Configuration=Release /p:Platform=Win32 /m /v:m /nologo
if ($LASTEXITCODE -ne 0) { throw "universal stager build failed (exit $LASTEXITCODE)" }

$out = Join-Path $Root "dist\universal_stager.exe"
if (-not (Test-Path $out)) { throw "universal stager output missing: $out" }
$hash = (Get-FileHash $out -Algorithm SHA256).Hash
$size = (Get-Item $out).Length
$x64Hash = (Get-FileHash $x64 -Algorithm SHA256).Hash
$x86Hash = (Get-FileHash $x86 -Algorithm SHA256).Hash
$line = "universal: $size bytes sha256 $hash`r`nembedded x64: $x64Hash`r`nembedded x86: $x86Hash"
$line | Set-Content (Join-Path $Root "dist\BUILD_UNIVERSAL.txt") -Encoding UTF8
Write-Host $line -ForegroundColor Green

if ($Test) {
    # The launcher exits after spawning the selected stager, so wait for the
    # child by launching it suspended-free and checking that the temp copy was
    # created and the child ran the selftest.
    $p = Start-Process -FilePath $out -ArgumentList '--selftest','--no-elevate' -Wait -PassThru -NoNewWindow
    if ($p.ExitCode -ne 0) { throw "universal launcher failed (exit $($p.ExitCode))" }
    Write-Host "[*] universal launcher spawned the selected stager" -ForegroundColor Green
}
